#!/usr/bin/env python3
"""Generates public/css/light.css from public/css/app.css.

The site is designed dark. This script reads every rule that uses a literal colour and writes a matching rule under
html[data-theme="light"] with the colours re-mapped for a light background:

  * greys and near-blacks/whites (low saturation) have their lightness flipped and get a warm paper tint
  * saturated colours (bronze, purple, green...) keep their hue; as text they are darkened so they stay readable
  * shadows are softened

Run it again after editing app.css:   python3 tools/make_light_theme.py
Rules that must keep their dark look (hero banner, buttons with dark text on bronze, avatars) are listed in KEEP.
"""
import colorsys, os, re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC, OUT = os.path.join(ROOT, "public/css/app.css"), os.path.join(ROOT, "public/css/light.css")
KEEP = (".hero", ".btn.primary", ".btn.danger", ".avatar", ".exit-reading", ".selin .sw", ".swatch", ".hl-", ".sw.", ".bar.aff", ".bar.opp",
        ".check.mini", ".steps-list li.done .check", ".days li.done .check", ".listpick.on .check")
HEX = re.compile(r"#[0-9a-fA-F]{8}\b|#[0-9a-fA-F]{6}\b|#[0-9a-fA-F]{3}\b")
RGB = re.compile(r"rgba?\(\s*([\d.]+)\s*,\s*([\d.]+)\s*,\s*([\d.]+)\s*(?:,\s*([\d.]+)\s*)?\)")
COLOR = re.compile(HEX.pattern + "|" + RGB.pattern)

LIGHT_VARS = """html[data-theme="light"]{
  --bg:#f5efe6; --bg2:#efe7db; --panel:#fffaf2; --panel2:#faf2e6; --line:rgba(110,72,36,.17); --line2:rgba(110,72,36,.32);
  --text:#241c17; --muted:#6c6157; --bronze:#9a5f2c; --bronze2:#7d4a1f; --champ:#7a4d22; --gold:#a97a2a; --purple:#6f55ad; --purple2:#5b4294;
  --danger:#b3392c; --ok:#3f7d44;
}
"""


def parse(c):
    if c.startswith("#"):
        h = c[1:]
        if len(h) == 3: h = "".join(x * 2 for x in h)
        r, g, b = (int(h[i:i + 2], 16) for i in (0, 2, 4)); a = int(h[6:8], 16) / 255 if len(h) == 8 else 1.0
        return r, g, b, a
    m = RGB.match(c)
    return float(m[1]), float(m[2]), float(m[3]), float(m[4]) if m[4] is not None else 1.0


def convert(c, prop):
    r, g, b, a = parse(c)
    h, l, s = colorsys.rgb_to_hls(r / 255, g / 255, b / 255)
    if s < 0.30:                                   # neutral: flip lightness, warm paper tone
        l2 = 1 - l
        h2, s2 = 35 / 360, min(0.30, max(s, 0.16)) if l2 > 0.5 else 0.14
        rr, gg, bb = colorsys.hls_to_rgb(h2, l2, s2)
    else:
        if prop == "color" and l > 0.5: l = min(l * 0.5, 0.36)   # accent used as text: darken
        rr, gg, bb = colorsys.hls_to_rgb(h, l, s)
    rr, gg, bb = (round(x * 255) for x in (rr, gg, bb))
    return f"rgba({rr},{gg},{bb},{a:.3g})" if a < 0.999 else f"#{rr:02x}{gg:02x}{bb:02x}"


def convert_decl(prop, value):
    if prop in ("box-shadow", "text-shadow"):       # keep dark, soften
        return RGB.sub(lambda m: f"rgba({m[1]},{m[2]},{m[3]},{float(m[4] or 1) * 0.4:.3g})", value)
    return COLOR.sub(lambda m: convert(m[0], prop), value)


def top_level_blocks(css):
    depth, start, sel_start, out = 0, 0, 0, []
    for i, ch in enumerate(css):
        if ch == "{":
            if depth == 0: start = i
            depth += 1
        elif ch == "}":
            depth -= 1
            if depth == 0:
                out.append((css[sel_start:start].strip(), css[start + 1:i])); sel_start = i + 1
    return out


def main():
    css = re.sub(r"/\*.*?\*/", "", open(SRC).read(), flags=re.S)
    rules, keep_rules = [], []
    for sel, body in top_level_blocks(css):
        if sel.startswith(("@", ":root")) or not COLOR.search(body): continue
        kept = [x.strip() for x in sel.split(",") if x.strip() and any(k in x for k in KEEP)]
        if kept: keep_rules.append(",".join('html[data-theme="light"] ' + x for x in kept) + "{" + body.strip() + "}")
        sels = [x.strip() for x in sel.split(",") if x.strip() and not any(k in x for k in KEEP)]
        if not sels: continue
        decls = []
        for d in re.split(r";(?![^(]*\))", body):
            if ":" not in d: continue
            prop, value = d.split(":", 1)
            if COLOR.search(value): decls.append(f"{prop.strip()}:{convert_decl(prop.strip(), value.strip())}")
        if decls:
            pre = lambda x: 'html[data-theme="light"] ' + (x if not x.startswith(("html", "body")) else x)
            rules.append(",".join(pre(x) for x in sels) + "{" + ";".join(decls) + "}")
    open(OUT, "w").write("/* GENERATED by tools/make_light_theme.py from app.css: do not edit by hand. */\n" + LIGHT_VARS + "\n".join(rules) + "\n/* rules that keep their dark look */\n" + "\n".join(keep_rules) + "\n"
        'html[data-theme="light"] body{background-image:linear-gradient(rgba(245,239,230,.95),rgba(245,239,230,.975)),url(/img/background.jpg)}\n'
        '\nhtml[data-theme="light"] .hero::after{background:linear-gradient(180deg,rgba(12,10,11,.2) 0%,rgba(12,10,11,0) 30%,rgba(245,239,230,.1) 62%,#f5efe6 100%),radial-gradient(ellipse at 50% 42%,rgba(12,10,11,.45),transparent 62%)}\n')
    print(f"wrote {OUT}: {len(rules)} rules")


if __name__ == "__main__":
    main()
